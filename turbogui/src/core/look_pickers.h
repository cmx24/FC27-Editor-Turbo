// FC 27 LE Turbo GUI - the registry of look pickers (5.0b-A). ONE entry per look attribute (database column); the Look card
// (ui_visual_picker.cpp look_card) is drawn FROM it for players and for managers, and the single write path (look_write) reads
// its Route. Memory feedback-one-picker-one-renderer: one picker and one catalogue per attribute, one renderer per subject.
//
// What lives here is DATA only (no ImGui, no App, no database): which column, its words, which subject has it, which kind of
// picker shows it, how a pick is written, and for hair and beard the ids of the 3D band. The pictures, swatches and labelled
// codes of an attribute are the visual picker's merged list (ui_visual_picker.cpp, vp: the ONE catalogue per field since 3.2, the
// game's pictures + RDBM26 + the labelled codes, built from the files the user has, so the core cannot list it), the 3D band
// writer is the faces gate's (ui_faces3d_gate.cpp, proven in game: CHANGELOG.md:115), the body writer is apply_bodytype.
//
// The manager rows are here and not in core/looks_fields_data.h on purpose: that file is GENERATED by research_20261017/
// gen_looks_fields.py from a census, and the census does not hold the manager's hair, beard, eye or skin columns. A manager has
// an attribute when its table has the column (the card skips an entry the loaded table lacks), so a database that gains a column
// gains the row.
//
// Hair and beard are ONE entry each (Kind::Band3D): the popup shows two sections, "Game hairstyles" (the vp merged list of the
// field: the generic head's hair) and "3D hairstyles (scanned heads)" (`band`: the generic ids a real face can take through the
// reserved band codes of core/faces3d.h). Platform independent.
#pragma once
#include <cstdint>
