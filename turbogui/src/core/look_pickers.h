// FC 27 LE Turbo GUI - the registry of look pickers (5.0b-A). ONE entry per look attribute (database column); the Look card
// (ui_visual_picker.cpp look_card) is drawn FROM it for players and for managers, and the single write path (look_write) reads
// its Route. Memory feedback-one-picker-one-renderer: one picker and one catalogue per attribute, one renderer per subject.
//
// What lives here is DATA only (no ImGui, no App, no database): which column, its words, which subject has it, which kind of
// picker shows it, how a pick is written, and for hair and beard the ids of the 3D band. The pictures, swatches and labelled
// codes of an attribute are the visual picker's merged list (ui_visual_picker.cpp, vp: the ONE catalogue per field since 3.2, the
// game's pictures + RDBM26 + the labelled codes, built from the files the user has, so the core cannot list it), the 3D band
// writer is the faces gate's (ui_faces3d_gate.cpp, proven in game: CHANGELOG.md:115), the body writer is apply_bodytype.
//
// The manager rows are here and not in core/looks_fields_data.h on purpose: that file is GENERATED by research_20261017/
// gen_looks_fields.py from a census, and the census does not hold the manager's hair, beard, eye or skin columns. A manager has
// an attribute when its table has the column (the card skips an entry the loaded table lacks), so a database that gains a column
// gains the row.
//
// Hair and beard are ONE entry each (Kind::Band3D): the popup shows two sections, "Game hairstyles" (the vp merged list of the
// field: the generic head's hair) and "3D hairstyles (scanned heads)" (`band`: the generic ids a real face can take through the
// reserved band codes of core/faces3d.h). Platform independent.
#pragma once
#include <cstdint>
#include <cstring>
#include <vector>

#include "core/faces3d.h"

namespace turbo::look {

enum Subject : uint8_t { kPlayer = 1, kManager = 2 };  // a mask in LookPicker::subjects

enum class Kind : uint8_t {
    RealFace,  // a real face of the game (headassetid): the chooser of ui_faces.cpp
    Band3D,    // hair / beard: game hairstyles AND the 3D band of the scanned heads, one popup, two sections
    Swatch,    // a colour: swatch tiles
    Pictures,  // a picture grid (RDBM26 picture, the game's own preview, or the names)
    Enum,      // a short labelled list (sleeves, sock length, complexion ...): the same popup, names only
    BodyType,  // the body-type gallery (pictures of the body-type generator, apply_bodytype's refusal rules)
    Tattoo,    // the tattoo editor (players only)
    Movement   // run style, free-kick and penalty run-ups: animated tiles
};

// How a pick reaches the database. Every route that ends in App::edit is one undo step and follows with faces3d_forget_render for
// the columns that change the 3D head (render_changes below).
enum class Route : uint8_t {
    AppEdit,       // visual_apply: App::edit (undo, kept edits, scoped edits); the 3D band section writes through the faces gate's own proven path
    BodyType,      // apply_bodytype(allow_risky = false): the refusal rules stay
    RealFace,      // the chooser (ui_faces.cpp real_face_picker / manager_real_face_picker): the head and its picture together
    TattooEditor   // tattoo_editor (ui_images.cpp)
};

// The generic ids the 3D band offers for a column (hair, beard); a pick writes faces3d::hair_band_code / beard_band_code of it
using BandFn = const std::vector<int>& (*)();

struct LookPicker {
    const char* column;  // database column; the registry key (exactly one entry per column)
    const char* label;   // the words on the card
    uint8_t subjects;    // Subject mask: which tables have this column
    Kind kind;
    const char* group;   // the card section
    Route route;
    BandFn band;         // "3D hairstyles (scanned heads)": hair and beard only; nullptr elsewhere
};

inline constexpr uint8_t kBoth = kPlayer | kManager;

// The card's sections, in order
inline constexpr const char* kGroups[] = {"Face", "Hair and beard", "Eyes and skin", "Body", "Tattoos", "Movement", "Kit and boots", "Accessories", "Outfit"};

inline const std::vector<LookPicker>& look_pickers() {
    // RED COMMIT (5.0b-A): the registry is declared and EMPTY, so test_look_pickers fails on the old behaviour (no picker rows for any subject).
    static const std::vector<LookPicker> v = {
    };
    return v;
}

// The entry of a column; nullptr when the column has no picker (it is typed in the card's "All fields" fold)
inline const LookPicker* find(const char* column) {
    for (const LookPicker& p : look_pickers())
        if (column && std::strcmp(p.column, column) == 0) return &p;
    return nullptr;
}

// The entries a subject has (the card then skips those the loaded table lacks), in card order
inline std::vector<const LookPicker*> pickers_for(Subject s) {
    std::vector<const LookPicker*> out;
    for (const char* g : kGroups)
        for (const LookPicker& p : look_pickers())
            if ((p.subjects & s) && std::strcmp(p.group, g) == 0) out.push_back(&p);
    return out;
}

// Columns whose change alters the 3D render of the head (the chooser's picture, the capture): the single write path forgets that
// render for them (faces3d_forget_render)
inline bool render_changes(const char* column) {
    static const char* const k[] = {"headassetid", "headtypecode", "hairtypecode",  "haircolorcode",  "facialhairtypecode", "facialhaircolorcode",
                                    "eyebrowcode", "eyecolorcode", "skintonecode",  "skincomplexion", "bodytypecode"};
    for (const char* c : k)
        if (column && std::strcmp(c, column) == 0) return true;
    return false;
}

// ---- the two sections of the hair and beard popup
enum class Section : uint8_t { Game = 0, Band3D = 1 };
// "" when the section applies to his head, else the one line that says why it is greyed (the words of ui_faces3d_gate.cpp, which
// kept them since 2.16). headclasscode: 0 real face, 1 generic head, <0 unknown. Only the 3D band depends on the head: the game
// hairstyles stay writable on every head (they show once he has a generic head), so a pick is never refused by this.
inline const char* section_reason(Section s, int64_t headclasscode) {
    if (s == Section::Band3D) {
        if (headclasscode < 0) return "3D hair and beard are for real faces.";
        if (headclasscode != 0) return "3D hair and beard are for real faces. He has a generic head: use the game hairstyles.";
    }
    return "";
}

// The generic id of a band pick written as its band code (0 = not on the band list); `column` hairtypecode or facialhairtypecode
inline int64_t band_code(const char* column, int64_t generic_id) {
    if (column && std::strcmp(column, "hairtypecode") == 0) return faces3d::hair_band_code(generic_id);
    if (column && std::strcmp(column, "facialhairtypecode") == 0) return faces3d::beard_band_code(generic_id);
    return 0;
}

// The ids a hair or beard popup offers, tagged by section; the union is what the three pickers it replaced offered together
// (the gallery's list, the visual picker's merged list, the faces gate's band grid): tests compare it to them
struct TaggedId {
    Section section;
    int64_t id;  // section Game: the field's code; section Band3D: the generic id (written as its band code)
    bool operator<(const TaggedId& o) const { return section != o.section ? section < o.section : id < o.id; }
    bool operator==(const TaggedId& o) const { return section == o.section && id == o.id; }
};
// `game_codes` = the visual picker's merged list of the field (visual_picker_codes()), the one catalogue of the Game section
inline std::vector<TaggedId> popup_ids(const LookPicker& p, const std::vector<int64_t>& game_codes) {
    std::vector<TaggedId> out;
    for (int64_t c : game_codes) out.push_back({Section::Game, c});
    if (p.band)
        for (int id : p.band()) out.push_back({Section::Band3D, id});
    return out;
}

}  // namespace turbo::look
