#!/usr/bin/env python3
"""FC 27 LE Turbo GUI - generate src/core/le_loc_labels_data.h (core/field_labels.h) from Live Editor's own localization.

Live Editor names some game enumerations Turbo shows as words: the match weather (weather_N), player morale (morale_N) and
injury types (injuryname_N). Live Editor's loc file is not committed (it is Live Editor's), so the names are copied into a
data header once, with this script; rerun it after a Live Editor update.

usage: gen_loc_labels.py <Live Editor root, e.g. "C:\FC 27 Live Editor">
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "core", "le_loc_labels_data.h")
# (table key in field_labels.h, loc key prefix)
TABLES = [("weather", "weather_"), ("morale", "morale_"), ("injury", "injuryname_")]


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else r"C:\FC 27 Live Editor"
    path = os.path.join(root, "loc", "eng_us", "localize.json")
    with open(path, encoding="utf-8") as f:
        loc = json.load(f)
    flat = {}

    def walk(o):  # the file nests its sections; a key may repeat (the first wins)
        if isinstance(o, dict):
            for k, v in o.items():
                if isinstance(v, str):
                    flat.setdefault(k, v)
                else:
                    walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    walk(loc)
    lines = []
    counts = []
    for table, prefix in TABLES:
        rows = []
        for k, v in flat.items():
            m = re.fullmatch(re.escape(prefix) + r"(\d+)", k)
            if m and isinstance(v, str):
                rows.append((int(m.group(1)), v))
        rows.sort()
        counts.append(f"{table} {len(rows)}")
        for code, name in rows:
            name = name.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'    {{"{table}", {code}, "{name}"}},')
    text = (
        "// FC 27 LE Turbo GUI - enumeration names from Live Editor's localization (core/field_labels.h). GENERATED by\n"
        "// scripts/gen_loc_labels.py from loc/eng_us/localize.json (weather_N, morale_N, injuryname_N): do not edit.\n"
        f"// Tables: {', '.join(counts)}.\n"
        "#pragma once\n#include <cstdint>\n\nnamespace turbo::labels::data {\n\n"
        "struct LocNamed {\n    const char* table;  // the field_labels.h table key\n    int32_t code;\n    const char* name;\n};\n\n"
        "constexpr LocNamed kLocNamed[] = {\n" + "\n".join(lines) + "\n};\n\n}  // namespace turbo::labels::data\n"
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}: {', '.join(counts)}")


if __name__ == "__main__":
    main()
