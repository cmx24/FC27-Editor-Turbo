#!/usr/bin/env python3
"""FC 27 LE Turbo GUI - generate src/core/faces3d_data.h (core/faces3d.h: the 3D hair / beard picker).

Embeds, as Turbo-owned data:
  * the player_kit.lua TEMPLATE v4 (v3 + the live band rule, 2.16; research_20261017/FACES_LIVE_HAIR.md), TEMPLATE v3 (gate
    "follow", research/c2_lua_loader/README_v3.md) and TEMPLATE v2 (Turbo text + anchors only: stock line numbers, md5s of stock lines, byte columns; NO EA
    source) as one C string with escapes, so editors cannot turn its TABs into spaces;
  * the verified generic model ids: hair_ids.json / beard_ids.json entries with ok == true (mesh + colour + coeff resources
    exist for <id>_1_0; turbo_dev/research/faces_ids/REPORT.md). Ids only, no game data.

usage: gen_faces3d_data.py [--template T] [--template3 T3] [--template4 T4] [--hair H] [--beard B]
defaults: ../../../research/c2_lua_loader/player_kit_template_v2.lua, player_kit_template_v3.lua, player_kit_template_v4.lua,
          ../../../research/faces_ids/{hair,beard}_ids.json
"""
import argparse, hashlib, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
RESEARCH = os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", "research"))
OUT = os.path.join(HERE, "..", "src", "core", "faces3d_data.h")


def c_string(text):
    out, line = [], ""
    for ch in text:
        if ch == "\\":
            line += "\\\\"
        elif ch == '"':
            line += '\\"'
        elif ch == "\t":
            line += "\\t"
        elif ch == "\n":
            line += "\\n"
            out.append('"%s"' % line)
            line = ""
            continue
        elif ord(ch) < 32 or ord(ch) > 126:
            raise SystemExit("template: non-ASCII / control character %r" % ch)
        else:
            line += ch
    if line:
        out.append('"%s"' % line)
    return "\n    ".join(out)


def ok_ids(path):
    d = json.load(open(path, encoding="utf-8"))
    return sorted(int(k) for k, v in d.items() if v.get("ok") is True)


def id_rows(ids):
    rows = []
    for i in range(0, len(ids), 16):
        rows.append("    " + ", ".join(str(x) for x in ids[i:i + 16]) + ",")
    return "\n".join(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--template", default=os.path.join(RESEARCH, "c2_lua_loader", "player_kit_template_v2.lua"))
    ap.add_argument("--template3", default=os.path.join(RESEARCH, "c2_lua_loader", "player_kit_template_v3.lua"))
    ap.add_argument("--template4", default=os.path.join(RESEARCH, "c2_lua_loader", "player_kit_template_v4.lua"))
    ap.add_argument("--hair", default=os.path.join(RESEARCH, "faces_ids", "hair_ids.json"))
    ap.add_argument("--beard", default=os.path.join(RESEARCH, "faces_ids", "beard_ids.json"))
    a = ap.parse_args()
    raw = open(a.template, "rb").read()
    text = raw.decode("ascii").replace("\r\n", "\n")
    tmd5 = hashlib.md5(text.encode("ascii")).hexdigest()
    text3 = open(a.template3, "rb").read().decode("ascii").replace("\r\n", "\n")
    tmd5_3 = hashlib.md5(text3.encode("ascii")).hexdigest()
    text4 = open(a.template4, "rb").read().decode("ascii").replace("\r\n", "\n")
    tmd5_4 = hashlib.md5(text4.encode("ascii")).hexdigest()
    hair, beard = ok_ids(a.hair), ok_ids(a.beard)
    h = []
    h.append("// FC 27 LE Turbo GUI - faces3d data (core/faces3d.h). GENERATED by scripts/gen_faces3d_data.py: do not edit.")
    h.append("// Template: player_kit_template_v2.lua (LF) md5 %s, %d bytes: Turbo text + anchors only (no EA source)." % (tmd5, len(text)))
    h.append("// Template: player_kit_template_v3.lua (LF) md5 %s, %d bytes: Turbo text + anchors only (no EA source)." % (tmd5_3, len(text3)))
    h.append("// Template: player_kit_template_v4.lua (LF) md5 %s, %d bytes: Turbo text + anchors only (no EA source)." % (tmd5_4, len(text4)))
    h.append("// Verified generic ids (ok == true in turbo_dev/research/faces_ids): hair %d, beard %d." % (len(hair), len(beard)))
    h.append("#pragma once")
    h.append("")
    h.append("namespace turbo::faces3d::data {")
    h.append("")
    h.append('constexpr const char* kTemplateMd5 = "%s";' % tmd5)
    h.append("constexpr const char kTemplate[] =")
    h.append("    " + c_string(text) + ";")
    h.append("")
    h.append('constexpr const char* kTemplateV3Md5 = "%s";' % tmd5_3)
    h.append("constexpr const char kTemplateV3[] =")
    h.append("    " + c_string(text3) + ";")
    h.append("")
    h.append('constexpr const char* kTemplateV4Md5 = "%s";' % tmd5_4)
    h.append("constexpr const char kTemplateV4[] =")
    h.append("    " + c_string(text4) + ";")
    h.append("")
    h.append("constexpr int kHairOk[] = {")
    h.append(id_rows(hair))
    h.append("};")
    h.append("constexpr int kBeardOk[] = {")
    h.append(id_rows(beard))
    h.append("};")
    h.append("")
    h.append("}  // namespace turbo::faces3d::data")
    open(OUT, "w", encoding="ascii", newline="\n").write("\n".join(h) + "\n")
    print("wrote %s: template md5 %s, v3 %s, v4 %s, hair %d, beard %d" % (os.path.normpath(OUT), tmd5, tmd5_3, tmd5_4, len(hair), len(beard)))


if __name__ == "__main__":
    main()
