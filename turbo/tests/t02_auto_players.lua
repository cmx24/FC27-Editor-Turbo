H.case("pap_playstyles sets all traits for the PAP player", function()
    local ok, msg = H.turbo().run("pap_playstyles")
    H.eq(ok, true, msg)
    local rec = sim:find_row("players", "playerid", 1001)
    H.eq(sim:value("players", rec, "trait1"), (1 << 30) - 1, "trait1 max")
    H.eq(sim:value("players", rec, "icontrait1"), (1 << 30) - 1, "icontrait1")
    H.eq(sim:value("players", rec, "trait2"), 1535, "trait2")
    H.eq(sim:value("players", sim:find_row("players", "playerid", 1002), "trait1"), 0, "others untouched")
end)

H.case("pap_playstyles auto re-applies after the game resets traits", function()
    H.write_config({ auto = { pap_playstyles = { enabled = true } } })
    H.turbo().boot()
    local rec = sim:find_row("players", "playerid", 1001)
    sim:set_field(rec, sim.tables.players.trait1, 5)
    sim:fire("post__CareerModeEvent", 0, 29, 0)   -- POST_LOAD_PREPARE
    H.eq(sim:value("players", rec, "trait1"), (1 << 30) - 1, "re-applied")
end)

