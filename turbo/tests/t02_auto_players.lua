H.case("FC 27 bundled script bug: old event constant names are nil", function()
    require 'imports/career_mode/enums'
    H.eq(ENUM_CM_EVENT_MSG_DAY_PASSED, nil, "old name")
    H.eq(ENUM_FCEGameModesCM_EVENT_MSG_DAY_PASSED, 15, "new name")
    local events = require 'imports/turbo/core/events'
    H.eq(events.resolve("DAY_PASSED"), 15, "turbo resolves")
    H.eq(events.resolve("NOT_AN_EVENT"), nil, "unknown")
end)

H.case("boot with nothing enabled registers no handler (game launch does nothing)", function()
    local enabled = H.turbo().boot({ at_launch = true })
    H.eq(#enabled, 0, "none enabled")
    H.eq(#(sim.handlers["post__CareerModeEvent"] or {}), 0, "no handler")
    local n = 0
    for _ in pairs(TURBO_STATE.listeners) do n = n + 1 end
    H.eq(n, 0, "no automatic listeners")
    sim:fire("post__CareerModeEvent", 0, 15, 0)   -- DAY_PASSED
    H.eq(sim:count_calls("SetPlayerForm"), 0, "nothing applied")
end)

H.case("form_morale auto: applies at boot and on DAY_PASSED, ignores other events", function()
    H.write_config({ auto = { form_morale = { enabled = true, form = 90, morale = 80, fitness = 0 } } })
    local enabled = H.turbo().boot()
    H.eq(enabled[1], "form_morale", "enabled")
    H.eq(#sim.handlers["post__CareerModeEvent"], 1, "one handler")
    H.eq(sim:count_calls("SetPlayerForm"), 26, "applied at boot")
    sim:fire("post__CareerModeEvent", 0, 15, 0)   -- DAY_PASSED
    H.eq(sim:count_calls("SetPlayerForm"), 52, "applied on day passed")
    H.eq(sim:count_calls("SetPlayerMorale"), 52, "morale too")
    H.eq(sim:count_calls("SetPlayerFitness"), 0, "fitness 0 = untouched")
    sim:fire("post__CareerModeEvent", 0, 7, 0)    -- USER_MATCH_COMPLETED: not configured
    H.eq(sim:count_calls("SetPlayerForm"), 52, "other event ignored")
    H.eq(sim.calls.SetPlayerForm[1][2], 90, "form value")
    H.eq(sim.calls.SetPlayerMorale[1][2], 80, "morale value")
end)

H.case("re-running boot does not add a second handler", function()
    H.turbo().boot()
    dofile(H.LE .. "/lua/autorun/turbo_boot.lua")
    H.script("turbo_enable_auto")
    H.eq(#sim.handlers["post__CareerModeEvent"], 1, "still one handler")
end)

H.case("disabling form_morale stops it on the next event", function()
    H.write_config({ auto = { form_morale = { enabled = false } } })
    H.turbo().boot()
    local before = sim:count_calls("SetPlayerForm")
    sim:fire("post__CareerModeEvent", 0, 15, 0)
    H.eq(sim:count_calls("SetPlayerForm"), before, "no more calls")
end)

H.case("form_morale action validates ranges", function()
    H.write_config({ auto = { form_morale = { form = 101 } } })
    local ok, msg = H.turbo().run("form_morale")
    H.eq(ok, false); H.has(msg, "form must be 0 (leave alone) or 0..100")
    H.write_config({ auto = { form_morale = { form = 100, morale = 100, fitness = 96 } } })
    ok, msg = H.turbo().run("form_morale")
    H.eq(ok, false); H.has(msg, "fitness must be 0 (leave alone) or 5..95")
    H.write_config({ auto = { form_morale = { form = 100, morale = 0, fitness = 95 } } })
    local before = sim:count_calls("SetPlayerFitness")
    ok, msg = H.script("turbo_form_morale_apply")
    ok, msg = H.turbo().run("form_morale")
    H.eq(ok, true, msg)
    H.eq(sim:count_calls("SetPlayerFitness") - before, 52, "fitness applied twice x26")
end)

