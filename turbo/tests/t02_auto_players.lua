H.case("custom_headassets: empty map refused, map applied, unknown player reported", function()
    local ok, msg = H.turbo().run("custom_headassets")
    H.eq(ok, false); H.has(msg, "map is empty")
    H.write_config({ modules = { custom_headassets = { map = { ["1001"] = 158023, ["1003"] = 20801, ["777"] = 5 } } } })
    ok, msg = H.script("turbo_custom_headassets")
    ok, msg = H.turbo().run("custom_headassets")
    H.eq(ok, true, msg); H.has(msg, "updated 2 of 3"); H.has(msg, "not found: 777")
    local rec = sim:find_row("players", "playerid", 1001)
    H.eq(sim:value("players", rec, "headassetid"), 158023, "asset")
    H.eq(sim:value("players", rec, "hashighqualityhead"), 1, "hq")
    H.eq(sim:value("players", rec, "headclasscode"), 0, "class")
end)

