H.case("delete_generated_players lists without confirm, deletes with confirm", function()
    local ok, msg = H.turbo().run("delete_generated_players")
    H.eq(ok, true, msg); H.has(msg, "5 generated players found")
    H.eq(sim:count_calls("DeletePlayer"), 0, "nothing deleted")
    H.write_config({ modules = { delete_generated_players = { confirm = true } } })
    ok, msg = H.turbo().run("delete_generated_players")
    H.eq(ok, true, msg); H.has(msg, "deleted 5")
    H.eq(sim:find_row("players", "playerid", 460003), nil, "gone")
    H.ok(sim:find_row("players", "playerid", 1001) ~= nil, "others kept")
    ok, msg = H.turbo().run("delete_generated_players")
    H.has(msg, "no players with playerid >= 460000")
end)

