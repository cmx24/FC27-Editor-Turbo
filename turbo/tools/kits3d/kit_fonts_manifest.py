"""Names of the game's kit number fonts and jersey name fonts (Turbo 2.11 K1): READ-ONLY on the game.

What it reads: only the bundle manifests of every toc (asset NAMES, never texture or font data, nothing is extracted). The
game's own asset folders carry the id in their name:
    content/character/kitnumber/<name>_<id>/numbers_<id>_<digit>_color     kit number fonts   (teamkits.numberfonttype)
    content/character/jerseyfonts/<name>_<id>/font_<id>                    jersey name fonts  (teamkits.jerseynamefonttype)
(and the <name>_<id>_kit_brt / _launch_kit_brt / _font_brt bundle references of the same folders). The pairs <id> -> <name> are
the labels Turbo shows. The rule "folder id = database id" is an inference (no live teamkits value confirmed it yet; the
in-game proof compares Chelsea's live value with the id named "chelsea"). It fails when one id has two names, or when a
numbers_<id>_ file disagrees with its folder's id.

usage:
  python -I kit_fonts_manifest.py [--game DIR] [--out kit_fonts_manifest.txt] [--header turbogui/src/core/kit_fonts_data.h]
  python -I kit_fonts_manifest.py --names-from kit_fonts_manifest.txt --header kit_fonts_data.h      (no game needed)
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

DEFAULT_GAME = r"C:\Program Files\EA Games\EA SPORTS FC 27"
KINDS = {"kitnumber": "numberfont", "jerseyfonts": "namefont"}
DIR_RE = re.compile(r"^([a-z][a-z0-9_]*?)_(\d+)(?:_(?:launch_)?(?:kit|font)_brt(?:_blueprint)?)?$")
LEAF_RE = re.compile(r"^(?:numbers|font)_(\d+)(?:_\d+_color|_launch_font_brt(?:_blueprint)?)?$")


def parse_name(asset):
    """'content/character/kitnumber/nike_144/numbers_144_3_color' -> ('numberfont', 144, 'nike'); None for anything else."""
    p = asset.lower().split("/")
    if len(p) < 4 or p[0] != "content" or p[1] != "character" or p[2] not in KINDS:
        return None
    m = DIR_RE.match(p[3])
    if not m:
        return None
    name, ident = m.group(1), int(m.group(2))
    if len(p) > 4:
        lm = LEAF_RE.match(p[4])
        if lm and int(lm.group(1)) != ident:
            raise ValueError("%s: the file's id %s is not its folder's id %d" % (asset, lm.group(1), ident))
    return KINDS[p[2]], ident, name


def collect(assets):
    """{kind: {id: name}}; a second name for one id is an error."""
    out = {"numberfont": {}, "namefont": {}}
    for a in assets:
        r = parse_name(a)
        if not r:
            continue
        kind, ident, name = r
        have = out[kind].setdefault(ident, name)
        if have != name:
            raise ValueError("%s %d has two names: %s and %s" % (kind, ident, have, name))
    return out


def scan_game(game_root):
    import kit_chunks as kc  # noqa: E402
    fb = kc.fb
    game = fb.Game(game_root)
    names = set()
    for p in kc.list_tocs(game_root):
        with open(p, "rb") as f:
            d = f.read()
        try:
            bundles = fb.parse_toc_bundles(d)
        except Exception as e:
            print("%s: skipped (%s)" % (os.path.basename(p), e))
            continue
        for locs in bundles:
            if not locs:
                continue
            try:
                ebx, res, _chunks = kc.parse_manifest(kc.bundle_manifest_blob(game, locs))
            except Exception:
                continue
            for n in [x[0] for x in ebx] + [r[0] for r in res]:
                if "/kitnumber/" in n.lower() or "/jerseyfonts/" in n.lower():
                    names.add(n)
        print("%s: %d font/number asset names so far" % (os.path.basename(p), len(names)), flush=True)
    game.close()
    return sorted(names)


def write_manifest(path, found, note):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("# kit font names from the game's own bundle manifests (%s)\n" % note)
        f.write("# kind\tid\tname      numberfont = teamkits.numberfonttype (and, inferred, shortsnumberfonttype); namefont = teamkits.jerseynamefonttype\n")
        for kind in ("namefont", "numberfont"):
            for ident in sorted(found[kind]):
                f.write("%s\t%d\t%s\n" % (kind, ident, found[kind][ident]))


def read_manifest(path):
    out = {"numberfont": {}, "namefont": {}}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            kind, ident, name = line.rstrip("\n").split("\t")
            out[kind][int(ident)] = name
    return out


def write_header(path, found):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by turbo/tools/kits3d/kit_fonts_manifest.py from the game's bundle manifests: asset NAMES only\n")
        f.write("// (content/character/kitnumber/<name>_<id>, content/character/jerseyfonts/<name>_<id>). No font data, no pictures.\n")
        f.write("// id -> name is the folder suffix; that it equals the teamkits id is an inference (see kit_fonts.h).\n")
        f.write("#pragma once\n\nnamespace turbo {\nnamespace kitfonts_data {\n\nstruct Named {\n    int id;\n    const char* name;\n};\n\n")
        for sym, kind in (("kNameFonts", "namefont"), ("kNumberFonts", "numberfont")):
            f.write("inline constexpr Named %s[] = {\n" % sym)
            for ident in sorted(found[kind]):
                f.write('    {%d, "%s"},\n' % (ident, found[kind][ident]))
            f.write("};\n\n")
        f.write("}  // namespace kitfonts_data\n}  // namespace turbo\n")


def self_test():
    """Names parsed from asset names written the way the game's manifests write them (no game needed)."""
    assert parse_name("content/character/kitnumber/nike_144/numbers_144_3_color") == ("numberfont", 144, "nike")
    assert parse_name("content/character/kitnumber/nike_144_launch_kit_brt_blueprint") == ("numberfont", 144, "nike")
    assert parse_name("content/character/kitnumber/generic_9_kit_brt") == ("numberfont", 9, "generic")
    assert parse_name("content/character/kitnumber/lfp_ligue_1_200/numbers_200_0_color") == ("numberfont", 200, "lfp_ligue_1")
    assert parse_name("content/character/kitnumber/futfc24_number_260") == ("numberfont", 260, "futfc24_number")
    assert parse_name("content/character/jerseyfonts/chelsea_153/font_153") == ("namefont", 153, "chelsea")
    assert parse_name("content/character/jerseyfonts/chelsea_153/font_153_launch_font_brt_blueprint") == ("namefont", 153, "chelsea")
    assert parse_name("content/character/kit/kit_0/chelsea_5/home_0_0/jersey/x") is None
    assert parse_name("content/character/kitnumber") is None
    found = collect(["content/character/kitnumber/chelsea_291/numbers_291_1_color", "content/character/kitnumber/chelsea_291_launch_kit_brt",
                     "content/character/jerseyfonts/chelsea_153/font_153"])
    assert found == {"numberfont": {291: "chelsea"}, "namefont": {153: "chelsea"}}, found
    for bad in (["content/character/kitnumber/a_1/numbers_1_0_color", "content/character/kitnumber/b_1/numbers_1_0_color"],
                ["content/character/kitnumber/a_1/numbers_2_0_color"]):
        try:
            collect(bad)
        except ValueError:
            continue
        raise AssertionError("not refused: %s" % bad)
    print("kit_fonts_manifest self-test passed")
    return 0


def main(argv=None):
    if argv is None and "--self-test" in sys.argv:
        return self_test()
    ap = argparse.ArgumentParser()
    ap.add_argument("--game", default=DEFAULT_GAME)
    ap.add_argument("--out")
    ap.add_argument("--header")
    ap.add_argument("--names-from", help="a manifest this tool wrote: no game scan")
    a = ap.parse_args(argv)
    if a.names_from:
        found = read_manifest(a.names_from)
        note = "re-read"
    else:
        found = collect(scan_game(a.game))
        note = "read from %s" % a.game
    print("namefont: %d ids, numberfont: %d ids" % (len(found["namefont"]), len(found["numberfont"])))
    if a.out:
        write_manifest(a.out, found, note)
    if a.header:
        write_header(a.header, found)
    return 0


if __name__ == "__main__":
    sys.exit(main())
